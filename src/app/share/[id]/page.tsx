import { notFound } from 'next/navigation'
import { createAdminClient } from '@/lib/supabase/admin'
import SOWViewer from '@/components/SOWViewer'
import PrintButton from '@/components/PrintButton'
import { PROJECT_TYPE_LABELS } from '@/lib/types'
import Link from 'next/link'

export default async function SharePage({ params }: { params: { id: string } }) {
  const admin = createAdminClient()

  const { data: project } = await admin
    .from('projects')
    .select('id, title, project_type, scope_of_work, scope_generated_at, created_at')
    .eq('id', params.id)
    .not('scope_of_work', 'is', null)
    .single()

  if (!project) notFound()

  return (
    <div style={{ background: 'oklch(0.13 0.022 252)', minHeight: '100vh' }}>
      {/* Nav */}
      <nav className="sticky top-0 z-50 flex items-center justify-between px-6 md:px-12 h-16 no-print"
        style={{ background: 'oklch(0.13 0.022 252 / 0.9)', backdropFilter: 'blur(12px)', borderBottom: '1px solid oklch(0.20 0.022 252)' }}>
        <Link href="/" className="flex items-center gap-2">
          {/* eslint-disable-next-line @next/next/no-img-element */}
          <img src="/tags-logo.jpg" alt="TAGS" className="h-9 max-w-[120px] object-contain rounded-md" />
        </Link>
        <div className="flex items-center gap-2">
          <PrintButton />
          <Link href="/register"
            className="px-4 py-2 rounded-lg text-sm font-semibold text-white no-print"
            style={{ background: 'oklch(0.57 0.135 183)' }}>
            Create Your Own SOW →
          </Link>
        </div>
      </nav>

      <div className="max-w-4xl mx-auto px-6 md:px-12 py-12">
        {/* Header */}
        <div className="mb-8">
          <div className="flex items-center gap-2 mb-3">
            <span className="text-xs px-2 py-1 rounded-full font-medium"
              style={{ background: 'oklch(0.18 0.06 183)', color: 'oklch(0.72 0.12 183)', border: '1px solid oklch(0.28 0.08 183)' }}>
              Scope of Work
            </span>
            <span className="text-xs" style={{ color: 'oklch(0.45 0.015 252)' }}>
              Generated by TAGS — tagyourproject.com
            </span>
          </div>
          <h1 className="text-3xl font-bold text-white mb-2">{project.title}</h1>
          <p className="text-sm" style={{ color: 'oklch(0.55 0.02 252)' }}>
            {PROJECT_TYPE_LABELS[project.project_type as keyof typeof PROJECT_TYPE_LABELS]}
            {project.scope_generated_at && ` · Generated ${new Date(project.scope_generated_at).toLocaleDateString('en-US', { month: 'long', day: 'numeric', year: 'numeric' })}`}
          </p>
        </div>

        {/* SOW */}
        <div className="rounded-2xl overflow-hidden" style={{ border: '1px solid oklch(0.22 0.022 252)' }}>
          <div className="p-6 md:p-8" style={{ background: 'oklch(0.14 0.022 252)' }}>
            <SOWViewer text={project.scope_of_work!} />
          </div>
        </div>

        {/* CTA */}
        <div className="mt-10 rounded-2xl p-6 text-center no-print"
          style={{ background: 'oklch(0.17 0.022 252)', border: '1px solid oklch(0.30 0.08 183)' }}>
          <p className="text-sm font-semibold text-white mb-1">Need a Scope of Work for your own project?</p>
          <p className="text-xs mb-4" style={{ color: 'oklch(0.55 0.02 252)' }}>
            Property managers get 3 free SOWs. Homeowners pay $20 per scope.
          </p>
          <Link href="/register"
            className="inline-flex items-center gap-2 px-6 py-3 rounded-xl text-sm font-semibold text-white"
            style={{ background: 'oklch(0.57 0.135 183)' }}>
            Create Your Free Scope of Work →
          </Link>
        </div>
      </div>
    </div>
  )
}
